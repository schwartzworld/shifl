#!/usr/bin/env python3
"""Convert operations.txt drum patterns to a C pattern table."""
import re, sys

# Abbreviation → drum lane (DS_* slot from eng_drum.c)
# BD=0 HT=1 SN=2 CL/RS/HC=3 CH=4 OH=5 CY/MT=6 LT=7 CB/SH=8; AC=skip
ABBREV = {
    'BD': 0, 'HT': 1, 'SN': 2, 'CL': 3, 'HC': 3, 'RS': 3,
    'CH': 4, 'OH': 5, 'CY': 6, 'MT': 6, 'LT': 7, 'CB': 8, 'SH': 8,
}

def parse_row(s):
    """Parse a 16-step pattern string 'x-x-...' into a uint16_t bitmask."""
    bits = 0
    for i, c in enumerate(s[:16]):
        if c == 'x':
            bits |= (1 << i)
    return bits

def c_escape(name):
    return name.replace("'", "").replace('"', '').replace('\n', '')

ops_path = sys.argv[1] if len(sys.argv) > 1 else 'operations.txt'
with open(ops_path) as f:
    lines = f.readlines()

patterns = []  # list of (name, {lane: uint16_t})
cur_name = None
cur_lanes = {}

for line in lines:
    line = line.rstrip('\n')
    # Section header or blank: flush current pattern
    if line.startswith('#') or line.startswith('##'):
        continue
    if not line.strip():
        if cur_name and cur_lanes:
            patterns.append((cur_name, dict(cur_lanes)))
        cur_name = None
        cur_lanes = {}
        continue
    # Pattern name line (no ':'): start new pattern
    m = re.match(r'^([A-Z][A-Z0-9 \-\'\(\)/\.&]+)$', line.strip())
    if m:
        if cur_name and cur_lanes:
            patterns.append((cur_name, dict(cur_lanes)))
        cur_name = line.strip()
        cur_lanes = {}
        continue
    # Row: "XX: pattern"
    m = re.match(r'^([A-Z]+):\s*([x\-^]+)', line)
    if m and cur_name:
        abbrev = m.group(1)
        pat = m.group(2)
        if abbrev in ABBREV:
            lane = ABBREV[abbrev]
            bits = parse_row(pat)
            cur_lanes[lane] = cur_lanes.get(lane, 0) | bits  # OR if same lane used twice

if cur_name and cur_lanes:
    patterns.append((cur_name, dict(cur_lanes)))

# Output C
print("/* Auto-generated by tools/gen_drum_pats.py — do not edit */")
print("#define DPAT_COUNT %du" % len(patterns))
print()
print("typedef struct { const char *name; uint16_t lane[9]; } dpat_t;")
print()
print("static const dpat_t DPATS[DPAT_COUNT] = {")
for name, lanes in patterns:
    vals = [lanes.get(i, 0) for i in range(9)]
    hex_vals = ', '.join('0x%04X' % v for v in vals)
    safe = c_escape(name)
    print('    { "%s", { %s } },' % (safe, hex_vals))
print("};")
